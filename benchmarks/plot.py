def emit_test3_zkarche(rows: List[IterRow], out: Path) -> None:
    """High-load: per-iteration latency aggregated across all sessions — ZK-ARCHE.

    With 50×50 = 2500 points, scatter is unreadable. We bucket by iteration
    index (0..49 in each client's run) and plot the mean+max per bucket.
    """
    by_iter: Dict[int, List[float]] = {}
    for r in rows:
        if r.success and r.duration_ms is not None:
            by_iter.setdefault(r.iter, []).append(r.duration_ms)

    iters = sorted(by_iter.keys())
    means = [mean(by_iter[i]) for i in iters]
    maxes = [max(by_iter[i]) for i in iters] if iters else []

    yhi = _safe_max(maxes + means) * 1.15 if iters else 1.0

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tikzpicture}")
    body.append(r"\begin{axis}[")
    body.append(r"  width=\linewidth, height=6cm,")
    body.append(r"  xlabel={Iteration index (within each client's 50-run sequence)},")
    body.append(r"  ylabel={Latency (ms)},")
    body.append(r"  xmin=0, ymin=0, ymax=" + f"{yhi:.3f},")
    body.append(r"  grid=major, grid style={dashed,gray!30},")
    body.append(r"  legend style={at={(0.02,0.98)}, anchor=north west, font=\footnotesize},")
    body.append(r"  title={ZK-ARCHE — high load (50 clients × 50 authentications)},")
    body.append(r"]")
    if iters:
        body.append(rf"\addplot+[mark=*, mark size=1.0pt, color={PROTO_COLOR['zkarche']}]")
        body.append(rf"  coordinates {{ {' '.join(f'({i+1},{m:.6f})' for i,m in zip(iters,means))} }};")
        body.append(r"\addlegendentry{Mean across 50 clients}")
        body.append(rf"\addplot+[mark=none, color=red!60!black, dashed, thick]")
        body.append(rf"  coordinates {{ {' '.join(f'({i+1},{mx:.6f})' for i,mx in zip(iters,maxes))} }};")
        body.append(r"\addlegendentry{Max across 50 clients}")
    body.append(r"\end{axis}")
    body.append(r"\end{tikzpicture}")
    out.write_text("\n".join(body) + "\n")


def emit_comparison(
    by_test: Dict[str, Dict[str, List[float]]],   # by_test[test_name][proto] = list of latency ms
    out: Path,
) -> None:
    """Grouped bar chart: mean latency per protocol per test."""
    test_keys = ["test1_concurrent", "test2_sequential", "test3_highload"]
    test_labels = {
        "test1_concurrent": "Concurrent",
        "test2_sequential": "Sequential",
        "test3_highload":   "High-load",
    }

    # Compute means
    means: Dict[str, Dict[str, float]] = {}
    for tk in test_keys:
        means[tk] = {}
        for proto in PROTOS_ORDER:
            ds = by_test.get(tk, {}).get(proto, [])
            means[tk][proto] = mean(ds) if ds else 0.0

    yhi = max(
        (means[tk][p] for tk in test_keys for p in PROTOS_ORDER),
        default=1.0,
    ) * 1.20

    symbolic_x = ",".join(test_labels[tk] for tk in test_keys)

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tikzpicture}")
    body.append(r"\begin{axis}[")
    body.append(r"  ybar, width=\linewidth, height=6.5cm,")
    body.append(r"  bar width=10pt,")
    body.append(r"  ymin=0, ymax=" + f"{yhi:.3f},")
    body.append(r"  ylabel={Mean authentication latency (ms)},")
    body.append(r"  symbolic x coords={" + symbolic_x + "},")
    body.append(r"  xtick=data,")
    body.append(r"  enlarge x limits=0.25,")
    body.append(r"  grid=major, grid style={dashed,gray!30},")
    body.append(r"  legend style={at={(0.5,-0.18)}, anchor=north, legend columns=3, font=\footnotesize},")
    body.append(r"  nodes near coords={\pgfmathprintnumber[fixed,fixed zerofill,precision=2]{\pgfplotspointmeta}},")
    body.append(r"  every node near coord/.append style={font=\tiny, rotate=90, anchor=west},")
    body.append(r"  title={Mean latency comparison across ZK-ARCHE, EDHOC, and mTLS},")
    body.append(r"]")
    for proto in PROTOS_ORDER:
        coords = " ".join(f"({test_labels[tk]},{means[tk][proto]:.4f})" for tk in test_keys)
        body.append(rf"\addplot+[fill={PROTO_COLOR[proto]}, draw=black] coordinates {{ {coords} }};")
        body.append(rf"\addlegendentry{{{PROTO_DISPLAY[proto]}}}")
    body.append(r"\end{axis}")
    body.append(r"\end{tikzpicture}")
    out.write_text("\n".join(body) + "\n")


def emit_resource_bars(
    summaries_by_proto: Dict[str, Optional[dict]],
    metric_path: Tuple[str, ...],
    title: str,
    ylabel: str,
    out: Path,
    multiplier: float = 1.0,
) -> None:
    """Single-host bar chart for memory/CPU/energy across the three protocols."""
    values: Dict[str, float] = {}
    for proto in PROTOS_ORDER:
        s = summaries_by_proto.get(proto)
        v = float("nan")
        if s and s.get("resources"):
            ref = s["resources"]
            try:
                for k in metric_path:
                    ref = ref[k]
                v = float(ref) * multiplier
            except (KeyError, TypeError, ValueError):
                v = float("nan")
        if math.isnan(v):
            v = 0.0
        values[proto] = v

    yhi = max(values.values(), default=1.0) * 1.25 if any(values.values()) else 1.0

    symbolic_x = ",".join(PROTO_DISPLAY[p] for p in PROTOS_ORDER)

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tikzpicture}")
    body.append(r"\begin{axis}[")
    body.append(r"  ybar, width=\linewidth, height=6cm,")
    body.append(r"  bar width=22pt,")
    body.append(r"  ymin=0, ymax=" + f"{yhi:.4f},")
    body.append(rf"  ylabel={{{ylabel}}},")
    body.append(r"  symbolic x coords={" + symbolic_x + "},")
    body.append(r"  xtick=data,")
    body.append(r"  enlarge x limits=0.35,")
    body.append(r"  grid=major, grid style={dashed,gray!30},")
    body.append(r"  nodes near coords={\pgfmathprintnumber[fixed,precision=2]{\pgfplotspointmeta}},")
    body.append(r"  every node near coord/.append style={font=\footnotesize},")
    body.append(rf"  title={{{title}}},")
    body.append(r"]")
    coords = " ".join(f"({PROTO_DISPLAY[p]},{values[p]:.6f})" for p in PROTOS_ORDER)
    body.append(rf"\addplot+[fill=blue!30, draw=black] coordinates {{ {coords} }};")
    body.append(r"\end{axis}")
    body.append(r"\end{tikzpicture}")
    out.write_text("\n".join(body) + "\n")


def emit_resource_bars_multi(
    by_device: Dict[str, Dict[str, Optional[dict]]],   # by_device[device][proto] -> summary dict
    device_order: List[str],
    metric_path: Tuple[str, ...],
    title: str,
    ylabel: str,
    out: Path,
    multiplier: float = 1.0,
) -> None:
    """Multi-platform grouped bars: x-axis = device, one bar per protocol per group.

    This is the layout the thesis chapter actually uses for figures 4/5/6:
    "Across all platforms, memory usage remains below 9 MB" — a chart that
    needs to show all three platforms side-by-side with one bar per protocol
    within each platform group.
    """
    # Pull each (device, proto) value
    values: Dict[str, Dict[str, float]] = {}
    for d in device_order:
        values[d] = {}
        for p in PROTOS_ORDER:
            s = by_device.get(d, {}).get(p)
            v = 0.0
            if s and s.get("resources"):
                ref = s["resources"]
                try:
                    for k in metric_path:
                        ref = ref[k]
                    v = float(ref) * multiplier
                    if v != v:  # NaN guard
                        v = 0.0
                except (KeyError, TypeError, ValueError):
                    v = 0.0
            values[d][p] = v

    yhi_candidates = [values[d][p] for d in device_order for p in PROTOS_ORDER]
    yhi = max(yhi_candidates) * 1.25 if any(yhi_candidates) else 1.0

    # Short labels avoid x-axis crowding. We strip parenthetical RAM size etc.
    def _short(name: str) -> str:
        return name.split("(")[0].strip()

    symbolic_x = ",".join(_short(d) for d in device_order)

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tikzpicture}")
    body.append(r"\begin{axis}[")
    body.append(r"  ybar, width=\linewidth, height=6.5cm,")
    body.append(r"  bar width=10pt,")
    body.append(r"  ymin=0, ymax=" + f"{yhi:.4f},")
    body.append(rf"  ylabel={{{ylabel}}},")
    body.append(r"  symbolic x coords={" + symbolic_x + "},")
    body.append(r"  xtick=data,")
    body.append(r"  enlarge x limits=0.25,")
    body.append(r"  grid=major, grid style={dashed,gray!30},")
    body.append(r"  legend style={at={(0.5,-0.18)}, anchor=north, legend columns=3, font=\footnotesize},")
    body.append(r"  nodes near coords={\pgfmathprintnumber[fixed,precision=2]{\pgfplotspointmeta}},")
    body.append(r"  every node near coord/.append style={font=\tiny, rotate=90, anchor=west},")
    body.append(rf"  title={{{title}}},")
    body.append(r"]")
    for proto in PROTOS_ORDER:
        coords = " ".join(f"({_short(d)},{values[d][proto]:.6f})" for d in device_order)
        body.append(rf"\addplot+[fill={PROTO_COLOR[proto]}, draw=black] coordinates {{ {coords} }};")
        body.append(rf"\addlegendentry{{{PROTO_DISPLAY[proto]}}}")
    body.append(r"\end{axis}")
    body.append(r"\end{tikzpicture}")
    out.write_text("\n".join(body) + "\n")


def emit_summary_table(
    summaries_by_test_and_proto: Dict[str, Dict[str, Optional[dict]]],
    out: Path,
) -> None:
    r"""Comparative summary table — drop-in for \input."""
    # Latency range = (min over all tests of latency.min, max over all tests of latency.max)
    # CPU range = (min mean_cpu_pct across resource sample, max peak_cpu_pct)
    # Memory range = (peak_rss_mb min, peak_rss_mb max) — across the three resource entries (test4/5/6 are same)
    # Bytes mean = sent+recv mean over test1 (single auth)
    # RTT counts: hardcoded by protocol semantics
    rtt_count = {"zkarche": 2, "edhoc": "1--1.5", "mtls": "2--3"}

    rows: List[Tuple[str, str, str, str, str, str]] = []
    rows.append(("Protocol", "Latency (ms)", "CPU (\\%)", "Memory (MB)", "Bytes (B)", "RTT"))

    for proto in PROTOS_ORDER:
        # Latency range from test1/test2/test3
        all_min: List[float] = []
        all_max: List[float] = []
        for t in ("test1_concurrent", "test2_sequential", "test3_highload"):
            s = summaries_by_test_and_proto.get(t, {}).get(proto)
            if s and s.get("latency_ms") and s["n_success"] > 0:
                all_min.append(float(s["latency_ms"]["min"]))
                all_max.append(float(s["latency_ms"]["max"]))
        if all_min and all_max:
            lat_str = f"{min(all_min):.2f}--{max(all_max):.2f}"
        else:
            lat_str = "n/a"

        # Resource block from test4_memory (same as test5/test6)
        res_summary = summaries_by_test_and_proto.get("test4_memory", {}).get(proto)
        if res_summary and res_summary.get("resources"):
            rb = res_summary["resources"]
            mean_cpu = rb.get("mean_cpu_pct", float("nan"))
            peak_cpu = rb.get("peak_cpu_pct", float("nan"))
            cpu_str = f"{mean_cpu:.0f}--{peak_cpu:.0f}"
            mem = rb.get("peak_rss_mb", float("nan"))
            mem_str = f"{mem:.1f}"
        else:
            cpu_str = "n/a"
            mem_str = "n/a"

        # Bytes from test1
        bytes_summary = summaries_by_test_and_proto.get("test1_concurrent", {}).get(proto)
        if bytes_summary and bytes_summary.get("total_bytes_mean") is not None:
            try:
                bts = float(bytes_summary["total_bytes_mean"])
                bytes_str = f"$\\sim${bts:.0f}"
            except (TypeError, ValueError):
                bytes_str = "n/a"
        else:
            bytes_str = "n/a"

        rows.append((
            PROTO_DISPLAY[proto], lat_str, cpu_str, mem_str, bytes_str, str(rtt_count[proto]),
        ))

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tabular}{lccccc}")
    body.append(r"\hline")
    for i, row in enumerate(rows):
        body.append(" & ".join(row) + r" \\")
        if i == 0:
            body.append(r"\hline")
    body.append(r"\hline")
    body.append(r"\end{tabular}")
    out.write_text("\n".join(body) + "\n")


