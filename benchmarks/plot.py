PREAMBLE_NOTE = (
    "% Auto-generated by benchmarks/plot.py — do not edit by hand.\n"
    "% Requires \\usepackage{pgfplots} \\pgfplotsset{compat=1.18}\n"
)


def _coords(values: List[float]) -> str:
    return " ".join(f"({i+1},{v:.6f})" for i, v in enumerate(values))


def _safe_max(values: List[float], default: float = 1.0) -> float:
    if not values:
        return default
    return max(values)


def emit_test1_zkarche(rows: List[IterRow], out: Path) -> None:
    """Per-client latency for 50 concurrent clients (single auth) — ZK-ARCHE."""
    durations = successful_durations(rows)
    avg = mean(durations) if durations else 0.0
    yhi = _safe_max(durations + [avg]) * 1.15

    body = []
    body.append(PREAMBLE_NOTE)
    body.append(r"\begin{tikzpicture}")
    body.append(r"\begin{axis}[")
    body.append(r"  width=\linewidth, height=6cm,")
    body.append(r"  xlabel={Client \#},")
    body.append(r"  ylabel={Latency (ms)},")
    body.append(r"  xmin=0, ymin=0, ymax=" + f"{yhi:.3f},")
    body.append(r"  grid=major, grid style={dashed,gray!30},")
    body.append(r"  legend style={at={(0.02,0.98)}, anchor=north west, font=\footnotesize},")
    body.append(r"  title={ZK-ARCHE — 50 concurrent clients (single authentication)},")
    body.append(r"]")
    body.append(rf"\addplot+[only marks, mark size=1.4pt, color={PROTO_COLOR['zkarche']}]")
    body.append(rf"  coordinates {{ {_coords(durations)} }};")
    body.append(r"\addlegendentry{Per-client latency}")
    if durations:
        body.append(rf"\addplot+[mark=none, dashed, thick, color=black] coordinates {{(0,{avg:.3f}) ({len(durations)+1},{avg:.3f})}};")
        body.append(rf"\addlegendentry{{Mean = {avg:.3f}\,ms}}")
    body.append(r"\end{axis}")
    body.append(r"\end{tikzpicture}")
    out.write_text("\n".join(body) + "\n")


