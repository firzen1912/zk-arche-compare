    print(f"  cp {args.out_tex}/test_2_graph.tex      <thesis>/Graphs/test_2_graph.tex")
    print(f"  cp {args.out_tex}/test_3_graph.tex      <thesis>/Graphs/test_3_graph.tex")
    print(f"  cp {args.out_tex}/test_4_graph.tex      <thesis>/Graphs/test_4_graph.tex")
    print(f"  cp {args.out_tex}/test_5_graph.tex      <thesis>/Graphs/test_5_graph.tex")
    print(f"  cp {args.out_tex}/test_6_graph.tex      <thesis>/Graphs/test_6_graph.tex")
    print(f"  cp {args.out_tex}/comparison_graph.tex  <thesis>/Graphs/comparison_graph.tex")
    print(f"  cp {args.out_tex}/summary_table.tex     <thesis>/(wherever)")
    return 0


