r"""
Generate the thesis figures and summary table from collected results.

Inputs (produced by the test runners):
    benchmarks/results/raw/<test>_<proto>.csv      (per-iteration metrics)
    benchmarks/results/summary/<test>_<proto>.json (aggregated stats)

Outputs:
    benchmarks/graphs_tex/test_1_graph.tex          (Test 1 — ZK-ARCHE single-protocol)
    benchmarks/graphs_tex/test_2_graph.tex          (Test 2 — ZK-ARCHE single-protocol)
    benchmarks/graphs_tex/test_3_graph.tex          (Test 3 — ZK-ARCHE single-protocol)
    benchmarks/graphs_tex/comparison_graph.tex      (latency comparison: ZK vs EDHOC vs mTLS)
    benchmarks/graphs_tex/test_4_graph.tex          (peak RSS, grouped bars by protocol)
    benchmarks/graphs_tex/test_5_graph.tex          (peak/mean CPU%, grouped bars)
    benchmarks/graphs_tex/test_6_graph.tex          (per-auth energy mJ, grouped bars)
    benchmarks/graphs_tex/summary_table.tex         (drop-in for \input)
    benchmarks/plots/*.png                          (matplotlib previews, if available)

The .tex filenames match the chapter's `\input{Graphs/...}` references; copy
them into your thesis's `Graphs/` directory (or symlink) to publish.

Usage:
    python -m benchmarks.plot
    python -m benchmarks.plot --merge-hosts results/host_pi3.tar results/host_pi4.tar ...
        (the second form lets you combine results gathered from multiple hosts;
         see README for details)
"""

