PROTOS_ORDER = ("zkarche", "edhoc", "mtls")
PROTO_DISPLAY = {"zkarche": "ZK-ARCHE", "edhoc": "EDHOC", "mtls": "mTLS"}

# PGFPlots colours that align with the chapter's three protocols.
