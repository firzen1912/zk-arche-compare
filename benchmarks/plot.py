@dataclass
class IterRow:
    iter: int
    client_id: int
    success: bool
    duration_ms: Optional[float]
    sent_bytes: Optional[int]
    recv_bytes: Optional[int]
    wall_s: float


def load_csv(path: Path) -> List[IterRow]:
    if not path.exists():
        return []
    out: List[IterRow] = []
    with path.open() as f:
        r = csv.DictReader(f)
        for row in r:
            try:
                out.append(IterRow(
                    iter=int(row["iter"]),
                    client_id=int(row["client_id"]),
                    success=bool(int(row["success"])),
                    duration_ms=float(row["duration_ms"]) if row["duration_ms"] else None,
                    sent_bytes=int(row["sent_bytes"]) if row["sent_bytes"] else None,
                    recv_bytes=int(row["recv_bytes"]) if row["recv_bytes"] else None,
                    wall_s=float(row["wall_s"]),
                ))
            except (KeyError, ValueError):
                continue
    return out


def load_summary(path: Path) -> Optional[dict]:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError:
        return None


def successful_durations(rows: List[IterRow]) -> List[float]:
    return [r.duration_ms for r in rows if r.success and r.duration_ms is not None]


def mean(values: Iterable[float]) -> float:
    vs = list(values)
    return float("nan") if not vs else sum(vs) / len(vs)


